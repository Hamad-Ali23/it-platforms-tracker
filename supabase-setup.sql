-- IT Platforms Tracker full Supabase setup (safe to re-run; does not overwrite existing platform rows).
-- IT Platforms Tracker: run this once in Supabase (SQL Editor > New query > Run)



create table if not exists platforms (

  id text primary key,

  name text not null,

  category text not null,

  assignee text,

  learn text,

  gamified text,

  cost text,

  url text,

  is_custom boolean default false,

  is_extra boolean default false,

  status text not null default 'todo' check (status in ('todo','doing','done')),

  services text default '',

  our_idea text default '',

  updated_by text,

  updated_at timestamptz,

  sort int default 0

);



-- Add note/update columns to an existing installation without deleting any saved data.
alter table public.platforms add column if not exists services text default '';
alter table public.platforms add column if not exists our_idea text default '';
alter table public.platforms add column if not exists updated_by text;
alter table public.platforms add column if not exists updated_at timestamptz;
alter table public.platforms add column if not exists is_custom boolean default false;
alter table public.platforms add column if not exists is_extra boolean default false;
alter table public.platforms add column if not exists status text not null default 'todo';
alter table public.platforms add column if not exists sort int default 0;


create table if not exists ideas (

  id bigint generated always as identity primary key,

  title text not null,

  details text,

  author text,

  created_at timestamptz default now()

);



create table if not exists settings (

  key text primary key,

  value text

);



-- The current website uses the Supabase anon key without sign-in.
-- These policies let anyone with the public site URL read/write tracker data.
-- For sensitive data, enable Supabase Auth and restrict these policies to trusted users.
alter table public.platforms enable row level security;
alter table public.ideas enable row level security;
alter table public.settings enable row level security;

drop policy if exists "team all platforms" on public.platforms;
create policy "team all platforms" on public.platforms for all to anon, authenticated using (true) with check (true);
drop policy if exists "team all ideas" on public.ideas;
create policy "team all ideas" on public.ideas for all to anon, authenticated using (true) with check (true);
drop policy if exists "team all settings" on public.settings;
create policy "team all settings" on public.settings for all to anon, authenticated using (true) with check (true);

-- Evidence file records: the actual images/PDFs/videos live in Supabase Storage.
create table if not exists public.platform_evidence (
  id bigint generated by default as identity primary key,
  platform_id text not null,
  file_path text not null unique,
  file_name text not null,
  mime_type text not null default 'application/octet-stream',
  size_bytes bigint not null default 0,
  caption text not null default '',
  uploaded_by text not null default 'Someone',
  uploaded_at timestamptz not null default now()
);
create index if not exists platform_evidence_platform_id_uploaded_at_idx
  on public.platform_evidence (platform_id, uploaded_at desc);
alter table public.platform_evidence enable row level security;
drop policy if exists "Tracker can read platform evidence" on public.platform_evidence;
create policy "Tracker can read platform evidence" on public.platform_evidence
  for select to anon, authenticated using (true);
drop policy if exists "Tracker can upload platform evidence metadata" on public.platform_evidence;
create policy "Tracker can upload platform evidence metadata" on public.platform_evidence
  for insert to anon, authenticated with check (true);
drop policy if exists "Tracker can delete platform evidence metadata" on public.platform_evidence;
create policy "Tracker can delete platform evidence metadata" on public.platform_evidence
  for delete to anon, authenticated using (true);

