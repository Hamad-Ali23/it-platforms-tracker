-- Enable realtime safely (skip if the publication is not available).
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='platforms') then
      execute 'alter publication supabase_realtime add table public.platforms';
    end if;
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='ideas') then
      execute 'alter publication supabase_realtime add table public.ideas';
    end if;
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='settings') then
      execute 'alter publication supabase_realtime add table public.settings';
    end if;
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='platform_evidence') then
      execute 'alter publication supabase_realtime add table public.platform_evidence';
    end if;
  end if;
end $$;

